#!/usr/bin/env python3
"""Write structure_bits.tex (to the path given, default structure_bits.tex): the field widths of every ms2-min, ms2-psi,
ms2-phi and ms2-dual structure for HPRC2, mtb152 and the chr22 indexes, as read from the ORBITIDX
headers by `ms index-plan` (ms2 binary ec43f8d, 2026-10-28).  MB = rows x bits / 8 / 1e6, the packed rows only."""

import math
import sys

# Each dataset: name, n, r, the lex-space rows, the text-space rows, the start
# tables' shift, and the ms2-min spillover arrays' bytes.
#   ms:   (rows, len, ptr, off, chr, top, sub, spill)
#   tms:  rows of LF with psi, rows of LF without it, the LF move widths
#         (len, ptr, off, chr) of each, psi (int, off), phi int
#   text: (rows, len, ptr, off, plcp, starts width)
DATASETS = [
    dict(name="HPRC2, 472 haps", n=2842375961968, r=5259024318,
         ms=(5305199950, 13, 33, 13, 3, 10, 2, 29),
         psi_rows=7671181822, psi_move=(13, 33, 13, 3), psi=(33, 13),
         phi_rows=5305199950, phi_move=(13, 33, 13, 3), phi_int=33,
         text=(5833432723, 13, 33, 13, 25, 42), shift=11, spill=22929487431),
    dict(name="mtb152, 144 genomes", n=1270896998, r=6705731,
         ms=(6708973, 11, 23, 11, 3, 4, 1, 17),
         psi_rows=8885287, psi_move=(11, 24, 11, 3), psi=(24, 11),
         phi_rows=6708973, phi_move=(11, 23, 11, 3), phi_int=23,
         text=(7916693, 11, 23, 11, 22, 31), shift=10, spill=5229046),
    dict(name="100 chr22s", n=10102453369, r=69247803,
         ms=(69887548, 11, 27, 11, 3, 7, 2, 22),
         psi_rows=100338483, psi_move=(11, 27, 11, 3), psi=(27, 11),
         phi_rows=69887548, phi_move=(11, 27, 11, 3), phi_int=27,
         text=(77962730, 11, 27, 11, 22, 34), shift=10, spill=190886431),
    dict(name="10 chr22s", n=1016136630, r=52798786,
         ms=(53351779, 8, 26, 8, 3, 5, 1, 20),
         psi_rows=72617511, psi_move=(8, 27, 8, 3), psi=(27, 8),
         phi_rows=53351779, phi_move=(8, 26, 8, 3), phi_int=26,
         text=(60194296, 8, 26, 8, 18, 30), shift=7, spill=39565346),
]


def num(x, places=0):
    s = f"{x:,.{places}f}"
    return s.replace(",", "{,}")


def rows_m(rows):
    m = rows / 1e6
    return num(m, 1 if m >= 1000 else 2) + "M"


def mb(rows, bits):
    v = rows * bits / 8 / 1e6
    return num(v, 1 if v < 100 else 0)


def size(x, unit):
    if unit == "G":
        v = x / 1e9
    else:
        v = x / 1e6
    places = 1 if v >= 1000 else 2 if v >= 10 else 3
    return num(v, places) + unit


def nr(d):
    nu = "G" if d["n"] >= 1e9 else "M"
    ru = "G" if d["r"] >= 1e9 else "M"
    sn, sr = size(d["n"], nu), size(d["r"], ru)
    return f"$n = {sn[:-1]}${sn[-1]}, $r = {sr[:-1]}${sr[-1]}"


D = "--"
lines = []
add = lines.append
add(r"""% Generated by ms2exp/figures/structure_bits.py in langmead-lab/ms2-experiments; regenerate there
% rather than editing.
% Field widths of the ms2-min, ms2-psi, ms2-phi and ms2-dual structures, from the ORBITIDX
% headers of the indexes used in the paper (ms index-plan, binary ms-ec43f8d,
% 2026-10-28).  MB = rows x bits / 8 / 1e6,
% the packed rows only (each table adds about 100 bytes of preamble and 8 of
% slack).  "HPRC2, 472 haps" is human472 (the FMD text: every contig and its
% reverse complement, each ending in $, N kept); mtb152 is Li's ropebwt3 index
% of 144 of the 152 M. tuberculosis genomes, both strands; "100 chr22s" and
% "10 chr22s" are the chr22-h100 and chr22-h10 indexes.
% LF's phi off column has width 0 in indexes built by tms-build from Orbit
% idxfmt 51823f3 on, since queries read phi points only at run heads, where
% the offset is 0.  The mtb152 files were built that way.  The HPRC2 and chr22
% files are rewraps of earlier builds and carry 1 bit there (HPRC2) or the LF
% offset width (11 for 100 chr22s, 8 for 10 chr22s); the table gives the
% current builds' widths.  HPRC2 has no psi-layout file; its LF+psi row is the
% full layout's LF without the phi link.
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{@{}lr rrrr rrr rr rr rr@{}}
 & & \multicolumn{4}{c}{Move fields}
   & \multicolumn{3}{c}{LCP (ms2-min)}
   & \multicolumn{2}{c}{$\psi$ link}
   & \multicolumn{2}{c}{$\phi$ link}
   & \multicolumn{2}{c}{Total} \\
\cmidrule(lr){3-6}\cmidrule(lr){7-9}\cmidrule(lr){10-11}\cmidrule(lr){12-13}\cmidrule(l){14-15}
Lex space & Rows & len & ptr & off & chr & top & sub & spill & int & off & int & off & bits & MB \\""")


def row(label, rows, cells):
    bits = sum(c for c in cells if isinstance(c, int))
    body = " & ".join(str(c) for c in cells)
    return f"{label:<30} & {rows_m(rows):>10} & {body} & {bits} & {mb(rows, bits)} \\\\"


for d in DATASETS:
    add(r"\midrule")
    add(rf"\multicolumn{{15}}{{@{{}}l}}{{\emph{{{d['name']}}} ({nr(d)})}} \\")
    ms = d["ms"]
    add(row("ms2-min LF", ms[0], list(ms[1:]) + [D, D, D, D]))
    pm, (pi, po), qi = d["psi_move"], d["psi"], d["phi_int"]
    add(row(r"ms2-psi LF+$\psi$", d["psi_rows"], list(pm) + [D, D, D, pi, po, D, D]))
    add(row(r"ms2-dual LF+$\psi$+$\phi$", d["psi_rows"], list(pm) + [D, D, D, pi, po, qi, 0]))
    add(row(r"ms2-phi LF+$\phi$", d["phi_rows"], list(d["phi_move"]) + [D, D, D, D, D, qi, 0]))

add(r"""\midrule
 & & \multicolumn{4}{c}{Move fields} & & & & & & & & \multicolumn{2}{c}{Total} \\
\cmidrule(lr){3-6}\cmidrule(l){14-15}
Text space & Rows & st/len & ptr & off & plcp & & & & & & & & bits & MB \\""")


def trow(label, rows, cells):
    bits = sum(cells)
    body = " & ".join(str(c) for c in cells)
    return f"{label:<30} & {rows_m(rows):>10} & {body} & & & & & & & & {bits} & {mb(rows, bits)} \\\\"


for d in DATASETS:
    rows, ln, ptr, off, plcp, st = d["text"]
    add(r"\midrule")
    add(rf"\multicolumn{{15}}{{@{{}}l}}{{\emph{{{d['name']}}}}} \\")
    add(trow(r"$\phi$ (lengths)", rows, [ln, ptr, off, plcp]))
    add(trow(r"$\phi$ (starts)", rows, [st, ptr, off, plcp]))
    add(trow(r"$\phi^{-1}$", rows, [st, ptr, off, plcp]))

add(r"\end{tabular}")

with open(sys.argv[1] if len(sys.argv) > 1 else "structure_bits.tex", "w") as f:
    f.write("\n".join(lines) + "\n")
